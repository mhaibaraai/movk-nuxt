import type { z } from 'zod'
import type { IsComponent } from '@movk/core'
import type { AutoFormControl, AutoFormControls, AutoFormField, AutoFormMergeMeta } from '../../types/auto-form'
import { markRaw } from 'vue'
import { joinPath, startCase, toPath, isFunction, isObject } from '@movk/core'
import { getAutoFormMetadata } from './metadata'
import type { ZodAutoFormFieldMeta } from '../../types/zod'
import { AUTOFORM_LIMITS, AUTOFORM_META } from './constants'

/** 获取 schema 的内层类型（optional/default/pipe 等包装的内部 schema） */
function getUnwrappedSchema(schema: any): z.ZodType | undefined {
  const def = schema?.def || schema?._def
  return def?.innerType || def?.in || def?.schema || undefined
}

/** 剥离 optional/readonly/default 等装饰层，返回装饰信息和核心 schema */
function extractDecorators(schema: z.ZodType): {
  decorators: AutoFormField['decorators']
  coreSchema: z.ZodType
} {
  const decorators: AutoFormField['decorators'] = {}
  let cur: any = schema
  let coreSchema: z.ZodType = schema

  while (cur) {
    const def = cur?.def || cur?._def
    if (!def?.type)
      break
    switch (def.type) {
      case 'optional':
        decorators.isOptional = true
        break
      case 'readonly':
        decorators.isReadonly = true
        break
      case 'default':
        decorators.defaultValue = isFunction(def.defaultValue)
          ? def.defaultValue()
          : def.defaultValue
        break
    }

    const next = getUnwrappedSchema(cur)
    if (!next)
      break

    if (next === cur)
      break

    cur = next
    coreSchema = next
  }

  /**
   * @deprecated z.describe() 已废弃，建议使用 z.meta({ description: '...' }) 代替
   * @see https://zod.dev/metadata?id=describe
   */
  if (coreSchema.description) {
    decorators.description = coreSchema.description
  }

  return { decorators, coreSchema }
}

/** 合并全局 meta、字段自定义 meta 与装饰器信息，确定最终渲染类型 */
function extractSchemaInfo(schema: z.ZodType, globalMeta: ZodAutoFormFieldMeta, autoGeneratedLabel: string) {
  const customMeta = getAutoFormMetadata(schema)
  const { decorators, coreSchema } = extractDecorators(schema)
  const computedType = customMeta?.component ? undefined : (customMeta?.type ?? (coreSchema as any)?.type)

  const mergedMeta = {
    ...{
      required: !decorators.isOptional,
      description: decorators.description,
      label: autoGeneratedLabel
    } as AutoFormField['meta'],
    ...globalMeta,
    ...customMeta,
    type: computedType,
    ...(customMeta?.overwrite && isObject(customMeta.overwrite) ? customMeta.overwrite : {})
  } as AutoFormMergeMeta

  return { decorators, mergedMeta, coreSchema }
}

/** 根据 meta.component 或 type 映射找到对应的渲染控件 */
function selectComponent(
  mergedMeta: AutoFormMergeMeta,
  finalType: string | undefined,
  mapping: AutoFormControls
): { chosenComponent: IsComponent | undefined, mapped: AutoFormControl<IsComponent> | undefined } {
  let chosenComponent: IsComponent | undefined
  let mapped: AutoFormControl<IsComponent> | undefined

  if (mergedMeta.component) {
    chosenComponent = mergedMeta.component
  } else if (finalType && finalType in mapping) {
    mapped = mapping[finalType as keyof typeof mapping]
    chosenComponent = mapped?.component
  }

  if (chosenComponent && typeof chosenComponent !== 'string') {
    chosenComponent = markRaw(chosenComponent)
  }

  return { chosenComponent, mapped }
}

/** 从枚举 schema 中提取所有可选值 */
function extractEnumValues(schema: z.ZodType): Array<string | number> | undefined {
  if ((schema as any).enum && typeof (schema as any).enum === 'object') {
    return Object.values((schema as any).enum)
  }

  const def = (schema as any)._def
  if (def?.values) {
    return Array.isArray(def.values) ? def.values : Array.from(def.values)
  }

  return undefined
}

/** 处理数组类型字段，递归解析元素 schema 并挂载到 field.arrayElement */
function handleArrayField(params: {
  schema: z.ZodType
  path: string
  decorators: AutoFormField['decorators']
  meta: AutoFormMergeMeta
  mapping: AutoFormControls
  globalMeta: ZodAutoFormFieldMeta
}): AutoFormField[] {
  const { schema, path, decorators, meta, mapping, globalMeta } = params
  const elementSchema = (schema as any).unwrap?.()

  if (!elementSchema) {
    return []
  }

  const field: AutoFormField = { path, schema, decorators, meta: { ...meta, type: 'array' } }

  const [arrayElement] = introspectSchema(elementSchema, mapping, path, globalMeta)

  if (arrayElement) {
    field.arrayElement = arrayElement
  }

  return [field]
}

/** 处理对象类型字段：根路径时扁平化展开，否则生成带 children 的嵌套字段 */
function handleObjectField(params: {
  schema: z.ZodType
  path: string
  decorators: AutoFormField['decorators']
  meta: AutoFormMergeMeta
  mapping: AutoFormControls
  globalMeta: ZodAutoFormFieldMeta
}): AutoFormField[] {
  const { schema, path, decorators, meta, mapping, globalMeta } = params
  const shape = (schema as any).shape

  if (!shape || typeof shape !== 'object') {
    return []
  }

  const shapeKeys = Object.keys(shape)

  if (shapeKeys.length > AUTOFORM_LIMITS.MAX_OBJECT_PROPERTIES) {
    return []
  }

  if (!path) {
    return shapeKeys.flatMap(key =>
      introspectSchema(shape[key] as z.ZodType, mapping, key, globalMeta)
    )
  }

  const field: AutoFormField = { path, schema, decorators, meta }
  field.children = shapeKeys.flatMap((key) => {
    const childPath = joinPath([...toPath(path), key])
    return introspectSchema(shape[key] as z.ZodType, mapping, childPath, globalMeta)
  })

  return [field]
}

/** 处理布局字段，将 meta.layout.fields 解析为子字段并挂载到 children */
function handleLayoutField(params: {
  schema: z.ZodType
  path: string
  meta: AutoFormMergeMeta
  mapping: AutoFormControls
  globalMeta?: ZodAutoFormFieldMeta
}): AutoFormField[] {
  const { schema, path, meta, mapping, globalMeta = {} } = params
  const shape = meta?.layout?.fields as Record<string, z.ZodType> | undefined

  if (!shape || typeof shape !== 'object') {
    return []
  }

  const pathSegments = toPath(path)
  const actualParentPath = pathSegments.slice(0, -1).join('.')
  const layoutField: AutoFormField = { path, schema, decorators: {}, meta }

  layoutField.children = Object.keys(shape).flatMap((key) => {
    const childSchema = shape[key]
    if (!childSchema) return []

    const childPath = actualParentPath ? `${actualParentPath}.${key}` : key
    return introspectSchema(childSchema, mapping, childPath, globalMeta)
  })

  return [layoutField]
}

/** 将 Zod schema 递归解析为 AutoFormField 列表（schema 遍历的核心入口） */
export function introspectSchema(
  schema: z.ZodType,
  mapping: AutoFormControls,
  path: string,
  globalMeta: ZodAutoFormFieldMeta = {}
): AutoFormField[] {
  // getter 定义的递归 schema 会无限展开，按路径深度截断
  if (toPath(path).length > AUTOFORM_LIMITS.MAX_RECURSION_DEPTH) return []

  const fieldName = path.split('.').pop()
  const autoGeneratedLabel = fieldName ? startCase(fieldName) : ''
  const { decorators, mergedMeta, coreSchema } = extractSchemaInfo(schema, globalMeta, autoGeneratedLabel)

  if (!coreSchema) {
    return []
  }

  const fieldType = mergedMeta.type

  if (fieldType === AUTOFORM_META.LAYOUT_KEY) {
    return handleLayoutField({ schema: coreSchema, path, meta: mergedMeta, mapping, globalMeta })
  }

  if (fieldType === 'array' || (coreSchema.type === 'array' && !mergedMeta.overwrite)) {
    return handleArrayField({ schema: coreSchema, path, decorators, meta: mergedMeta, mapping, globalMeta })
  }

  if (fieldType === 'object') {
    return handleObjectField({ schema: coreSchema, path, decorators, meta: mergedMeta, mapping, globalMeta })
  }

  const field: AutoFormField = { path, schema: coreSchema, decorators, meta: mergedMeta }
  const { chosenComponent, mapped } = selectComponent(mergedMeta, fieldType, mapping)

  field.meta.component = chosenComponent
  field.meta.mapped = mapped

  if (coreSchema.type === 'enum' && mapped) {
    const enumValues = extractEnumValues(coreSchema)
    if (enumValues && enumValues.length > 0) {
      field.meta.controlProps = {
        items: enumValues,
        ...(field.meta.controlProps as unknown as Record<string, unknown>)
      } as unknown as AutoFormMergeMeta['controlProps']
    }
  }

  return [field]
}

/** 判断 schema 是否为布局占位标记（type === '__layout__'） */
function isLayoutMarker(schema: z.ZodType): boolean {
  const meta = getAutoFormMetadata(schema)
  return meta?.type === AUTOFORM_META.LAYOUT_KEY
}

type ZodDefLike = { type?: string, shape?: Record<string, z.ZodType>, innerType?: z.ZodType, in?: z.ZodType }
type CloneableSchema = z.ZodType & { clone: (def: ZodDefLike) => z.ZodType }

function defOf(schema: z.ZodType): ZodDefLike {
  return (schema as unknown as { _zod: { def: ZodDefLike } })._zod.def
}

/**
 * 穿过 optional/nullable/default/readonly/pipe 等包装，替换最内层对象的 shape。
 * 经 `clone(def)` 重建，checks（refinement）、catchall 等定义原样保留。
 */
function mapObjectShape(
  schema: z.ZodType,
  mapShape: (shape: Record<string, z.ZodType>) => Record<string, z.ZodType> | undefined
): z.ZodType {
  const def = defOf(schema)
  const cloneable = schema as CloneableSchema

  if (def.type === 'object' && def.shape) {
    const shape = mapShape(def.shape)
    return shape ? cloneable.clone({ ...def, shape }) : schema
  }
  if (def.innerType) {
    const inner = mapObjectShape(def.innerType, mapShape)
    return inner === def.innerType ? schema : cloneable.clone({ ...def, innerType: inner })
  }
  if (def.type === 'pipe' && def.in) {
    const input = mapObjectShape(def.in, mapShape)
    return input === def.in ? schema : cloneable.clone({ ...def, in: input })
  }
  return schema
}

/** 展开 shape 中的布局标记，并递归处理嵌套对象；没有变化时返回 undefined */
function expandLayoutShape(shape: Record<string, z.ZodType>): Record<string, z.ZodType> | undefined {
  let changed = false
  const entries = Object.entries(shape).flatMap(([key, fieldSchema]): Array<[string, z.ZodType]> => {
    if (isLayoutMarker(fieldSchema)) {
      changed = true
      const layoutFields = getAutoFormMetadata(fieldSchema)?.layout?.fields
      if (!layoutFields || !isObject(layoutFields)) return []
      const expanded = expandLayoutShape(layoutFields as Record<string, z.ZodType>) ?? layoutFields
      return Object.entries(expanded as Record<string, z.ZodType>)
    }
    const next = mapObjectShape(fieldSchema, expandLayoutShape)
    if (next !== fieldSchema) changed = true
    return [[key, next]]
  })
  return changed ? Object.fromEntries(entries) : undefined
}

/** 将含布局标记的 schema 还原为纯字段 schema，用于 Zod 表单校验 */
export function extractPureSchema<T extends z.ZodObject<any, any>>(schema: T): z.ZodObject<any, any> {
  return mapObjectShape(schema, expandLayoutShape) as z.ZodObject<any, any>
}

type PathTree = Map<string, PathTree | true>

function buildPathTree(paths: string[]): PathTree {
  const root: PathTree = new Map()
  for (const path of paths) {
    const segments = toPath(path).map(String)
    let node = root
    segments.forEach((segment, index) => {
      if (index === segments.length - 1) {
        node.set(segment, true)
        return
      }
      const child = node.get(segment)
      if (child === true) return
      const next: PathTree = child ?? new Map()
      node.set(segment, next)
      node = next
    })
  }
  return root
}

function omitByTree(schema: z.ZodType, tree: PathTree): z.ZodType {
  return mapObjectShape(schema, (shape) => {
    const keys = Object.keys(shape)
    if (!keys.some(key => tree.has(key))) return undefined
    return Object.fromEntries(keys.flatMap((key): Array<[string, z.ZodType]> => {
      const node = tree.get(key)
      if (node === true) return []
      return [[key, node ? omitByTree(shape[key]!, node) : shape[key]!]]
    }))
  })
}

/**
 * 从校验 schema 中剔除指定路径（支持嵌套，如 `profile.phone`），
 * 用于让 meta.if 隐藏的字段不参与校验。refinement 保留，并以完整数据执行。
 */
export function omitPaths<T extends z.ZodType>(schema: T, paths: string[]): T {
  if (!paths.length) return schema
  return omitByTree(schema, buildPathTree(paths)) as T
}

type LengthCheckDef = { check?: string, minimum?: number, maximum?: number, length?: number }

/** 读取数组 schema 上的 `.min()` / `.max()` / `.length()` 约束 */
export function getArrayLengthBounds(schema: z.ZodType): { min: number, max: number } {
  const checks = (defOf(schema) as { checks?: Array<{ _zod: { def: LengthCheckDef } }> }).checks ?? []
  return checks.reduce((bounds, { _zod: { def } }) => {
    if (def.check === 'min_length') return { ...bounds, min: def.minimum ?? bounds.min }
    if (def.check === 'max_length') return { ...bounds, max: def.maximum ?? bounds.max }
    if (def.check === 'length_equals') return { min: def.length ?? bounds.min, max: def.length ?? bounds.max }
    return bounds
  }, { min: 0, max: Infinity })
}
